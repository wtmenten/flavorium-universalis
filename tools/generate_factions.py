def types_file() -> str:
    """One boolean character modifier type per archetype, carried by the member badge so the
    badge has something to show. Nothing in script or engine reads these."""
    p = [HEADER]
    for t in T:
        p.append(block(f"cc_pty_party_{t['key']}", [
            "color = neutral", "boolean = yes", "game_data = {", "\tcategory = character", "}"]))
        p.append("")
    return "\n".join(p) + "\n"


def _block_at(text: str, start: int) -> int:
    """Index just past the brace block opening at or after `start`."""
    i = text.index("{", start)
    depth = 0
    while True:
        c = text[i]
        depth += (c == "{") - (c == "}")
        i += 1
        if depth == 0:
            return i


def picker_file() -> str:
    """Override of vanilla's `character_info` (every character picker row derives from it,
    the cabinet appointment picker included) with the character's party icon after the role
    icon. Read from the installed game and patched, so rerunning the generator after an EU5
    update re-syncs it. Overriding a type from a new file does not shadow the vanilla file;
    another mod overriding the same type wins or loses by load order."""
    sys.path.insert(0, str(Path(__file__).resolve().parent))
    from game_paths import game_root

    src_path = Path(game_root()) / "in_game" / "gui" / "attribute_columns" / "character.gui"
    src = src_path.read_text(encoding="utf-8-sig")
    start = src.index("type character_info = clickable_header_card {")
    block = src[start:_block_at(src, start)]

    role = block.index("character_role_icon = {")
    role_end = _block_at(block, role)
    line_start = block.rfind("\n", 0, role) + 1
    indent = block[line_start:role]
    aff = "InteractionTarget.GetCharacter.MakeScope.GetVariable('cc_pty_aff').GetValue"
    icons = "".join(
        f'{indent}\ticon = {{ size = {{ 25 25 }}  texture = "{SEAT[t["key"]]["icon"]}"  '
        f'tooltip = "cc_pty_type_{t["key"]}"  visible = "[EqualTo_CFixedPoint({aff}, {fp(t["id"])})]" }}\n'
        for t in T)
    party = (f"\n\n{indent}# Factions: the character's party (cc_pty_aff), one fixed icon per party.\n"
             f"{indent}widget = {{\n{indent}\tsize = {{ 25 25 }}\n{icons}{indent}}}")
    block = block[:role_end] + party + block[role_end:]

    head = f"""######################################################################
# GENERATED by tools/generate_factions.py from the installed game's
# in_game/gui/attribute_columns/character.gui. Do not edit; rerun the generator, which also
# re-syncs this copy after an EU5 update.
#
# Vanilla's `character_info` type, unchanged except for the party icon added after the
# role icon. Every character picker row derives from this type (character_adm/dip/mil,
# character_ruler, character_general, ...), so a candidate's party shows wherever
# characters are chosen, the cabinet appointment picker included.
######################################################################

types CcPtyCharacterColumns
{{
	"""
    return head + block + "\n}\n"


