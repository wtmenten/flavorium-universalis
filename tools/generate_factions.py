def block(name: str, lines: list[str], indent: int = 0) -> str:
    pad = "\t" * indent
    out = [f"{pad}{name} = {{"]
    out += [f"{pad}\t{line}" for line in lines]
    out.append(f"{pad}}}")
    return "\n".join(out)


def fmt_val(v) -> str:
    if isinstance(v, str):
        return v
    s = f"{v:.4f}".rstrip("0").rstrip(".")
    return s


