                     f'visible = "[Not(EqualTo_CFixedPoint({fx}, {fp(0)}))]"  '
                     f'text_single = {{ minimumsize = {{ 44 -1 }}  fontsize = 10  align = right|nobaseline  text = "[{fx}|{fmt_spec(m)}]" }}  '
