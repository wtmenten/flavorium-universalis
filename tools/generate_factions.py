def sel(k: int) -> str:
    """Is card k selected? Slot 1 is selected until the player clicks a card."""
    has = f"SituationView.Vars.HasValue( 'cc_pty_sel', '{k}' )"
    if k == 1:
        return f"Or({has}, Not(SituationView.Vars.Exists( 'cc_pty_sel' )))"
    return has


def seat(i: int) -> str:
    """Seat i shows the party whose cumulative range covers it, or an empty seat."""
    lines = [f"\t\t\t\t\t\twidget = {{",
             f"\t\t\t\t\t\t\tsize = {{ {SEAT_PX} {SEAT_PX} }}",
             f"\t\t\t\t\t\t\tbackground = {{ using = color_whiteish_texture  alpha = 0.08 }}",
             f"\t\t\t\t\t\t\ticon = {{ size = {{ {SEAT_PX} {SEAT_PX} }}  alpha = 0.18  texture = \"gfx/interface/icons/flat_icons/parliament.dds\"  "
             f"visible = \"[Not(GreaterThanOrEqualTo_CFixedPoint({gv('cc_pty_chamber')}, {fp(i)}))]\" }}"]
    def vis(t):
        hi = gv(f"cc_pty_r{t['id']}_hi")
        lo = gv(f"cc_pty_r{t['id']}_lo")
        return f"And(GreaterThanOrEqualTo_CFixedPoint({hi}, {fp(i)}), Not(GreaterThanOrEqualTo_CFixedPoint({lo}, {fp(i)})))"
    lines.append(type_icons(SEAT_PX, vis, "\t\t\t\t\t\t\t").rstrip("\n"))
    lines.append("\t\t\t\t\t\t}")
    return "\n".join(lines) + "\n"


def seat_block(first: int) -> str:
    """Two columns x GRID_ROWS rows, seats numbered row by row from `first`."""
    out = ["\t\t\t\tvbox = {", "\t\t\t\t\tspacing = 2"]
    for r in range(GRID_ROWS):
        out.append("\t\t\t\t\thbox = {")
        out.append("\t\t\t\t\t\tspacing = 2")
        body = seat(first + 2 * r) + seat(first + 2 * r + 1)
        out.append(body.rstrip("\n"))
        out.append("\t\t\t\t\t}")
    out.append("\t\t\t\t\texpand = {}")
    out.append("\t\t\t\t}")
    return "\n".join(out) + "\n"


