def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="exit 1 if any output is out of date")
    args = ap.parse_args()
    stale = []
    for rel, fn in OUTPUTS.items():
        path = SUB / rel
        text = fn()
        # Every output carries a UTF-8 BOM, as the main mod's .txt, .yml and .gui files do.
        enc = "utf-8-sig"
        if args.check:
            cur = path.read_text(encoding=enc) if path.exists() else None
            if cur != text:
                stale.append(rel)
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding=enc, newline="\n")
        print(f"wrote {rel}")
    if args.check and stale:
        print("stale: " + ", ".join(stale))
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
