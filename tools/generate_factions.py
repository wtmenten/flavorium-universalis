def age_ge(age: str) -> str:
    return f"current_age_or_later = {{ age = {age} }}"


def age_lt(age: str) -> str:
    return f"NOT = {{ {age_ge(age)} }}"


def gov(g: str) -> str:
    return f"government_type = government_type:{g}"


def cgroup(g: str) -> str:
    return f"culture = {{ has_culture_group = culture_group:{g} }}"


def estate_power(e: str) -> str:
    return f'"estate_power(estate_type:{e}_estate)"'


def has_estate(e: str) -> str:
    return f"any_estate = {{ estate_type = estate_type:{e}_estate }}"


def sat_ge(e: str, v: float) -> str:
    return f"cc_pty_estate_sat_ge = {{ ESTATE = {e}_estate VALUE = {v} }}"


def estate_mood(e: str) -> list[str]:
    """Estate satisfaction mapped to -40..40 (0.5 satisfaction = 0)."""
    return [
        "value = 0",
        "if = {",
        f"\tlimit = {{ {has_estate(e)} }}",
        f"\tadd = estate_satisfaction:{e}_estate",
        "\tsubtract = 0.5",
        "\tmultiply = 80",
        "}",
    ]


