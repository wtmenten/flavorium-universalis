def dispatch(name: str, comment: str, inner, types=T) -> str:
    """if/else_if over the slot's archetype; inner(t) returns the call line."""
    lines = []
    for n, t in enumerate(types):
        kw = "if" if n == 0 else "else_if"
        lines += [f"{kw} = {{", f"\tlimit = {{ {slot_type('$SLOT$', t['id'])} }}", f"\t{inner(t)}", "}"]
    return f"# {comment}\n" + block(name, lines)


