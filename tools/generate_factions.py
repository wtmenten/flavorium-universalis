"""Generate the per-archetype files of the Factions submod (submods/factions).

The party catalogue below is the single source for everything that repeats once per
archetype or once per slot: script values, dispatch effects and triggers, static
modifiers, party names, the slot actions, the English loc for all of those, and the
Factions panel GUI. The hand-written logic (scripted_effects/cc_pty_effects.txt,
events, on_actions, disasters) calls into what this writes.

    python tools/generate_factions.py            # write all outputs
    python tools/generate_factions.py --check    # exit 1 if any output is stale

Archetype ids are saved into games (slot types, minister affiliations). Never renumber
an existing id; add new ones at the end.
"""

